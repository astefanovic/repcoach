import { useEffect, useState } from "react";

import { Plan as PlanRuntime } from "@repcoach/client-runtime";

/**
 * The **Exercise library**: ~1,300 exercises from the upstream exercises
 * dataset (hasaneyldrm/exercises-dataset), each with an animation. It is what
 * the picker browses and what a catalog row's `libraryId` points at.
 *
 * Reference material, not the Exercise catalog. The catalog stays the set of
 * exercises the user has actually used (ADR 0016); picking from the library
 * mints a catalog row that links back here, so the animation follows it
 * everywhere the exercise is shown.
 *
 * The metadata is vendored (`library.json`, regenerated by
 * `scripts/build-exercise-library.mjs`, pinned to one upstream commit). The
 * media is © Gym visual and is **not** vendored — it is loaded from that same
 * pinned commit through jsDelivr, so it needs a connection and the repo never
 * redistributes it.
 */

export interface LibraryExercise {
  readonly id: string;
  readonly name: string;
  readonly bodyPart: string;
  readonly equipment: string;
  readonly target: string;
  readonly secondary: ReadonlyArray<string>;
  /** The shared file stem of `images/<media>.jpg` and `videos/<media>.gif` upstream. */
  readonly media: string;
  readonly steps: ReadonlyArray<string>;
}

export interface ExerciseLibrary {
  readonly commit: string;
  readonly exercises: ReadonlyArray<LibraryExercise>;
  readonly byId: ReadonlyMap<string, LibraryExercise>;
}

export const LIBRARY_ATTRIBUTION = "Animations © Gym visual · gymvisual.com";

const mediaBase = (library: ExerciseLibrary) =>
  `https://cdn.jsdelivr.net/gh/hasaneyldrm/exercises-dataset@${library.commit}`;

/** The 180×180 still — cheap enough for list rows. */
export const thumbnailUrl = (library: ExerciseLibrary, exercise: LibraryExercise) =>
  `${mediaBase(library)}/images/${exercise.media}.jpg`;

/** The animated GIF (~100 KB) — for the detail view only. */
export const animationUrl = (library: ExerciseLibrary, exercise: LibraryExercise) =>
  `${mediaBase(library)}/videos/${exercise.media}.gif`;

let pending: Promise<ExerciseLibrary> | undefined;

/**
 * Loads the library once per page. A dynamic import, so the ~850 KB of JSON is
 * its own chunk and costs nothing until a picker first opens.
 */
export function loadExerciseLibrary(): Promise<ExerciseLibrary> {
  pending ??= import("./library.json").then((module) => {
    const data = module.default as unknown as Pick<ExerciseLibrary, "commit" | "exercises">;
    return {
      commit: data.commit,
      exercises: data.exercises,
      byId: new Map(data.exercises.map((exercise) => [exercise.id, exercise])),
    };
  });
  // A failed chunk load must not poison every later attempt.
  pending.catch(() => {
    pending = undefined;
  });
  return pending;
}

export type ExerciseLibraryState =
  | { readonly status: "loading" }
  | { readonly status: "ready"; readonly library: ExerciseLibrary }
  | { readonly status: "failed" };

export function useExerciseLibrary(): ExerciseLibraryState {
  const [state, setState] = useState<ExerciseLibraryState>({ status: "loading" });
  useEffect(() => {
    let disposed = false;
    loadExerciseLibrary().then(
      (library) => !disposed && setState({ status: "ready", library }),
      () => !disposed && setState({ status: "failed" }),
    );
    return () => {
      disposed = true;
    };
  }, []);
  return state;
}

