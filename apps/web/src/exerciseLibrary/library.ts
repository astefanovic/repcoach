/**
 * How well a library exercise matches the query — the catalog's own ranking
 * over the name, so a typed query orders the two lists the same way, with one
 * looser tier after it: the query found in the exercise's body part, target
 * muscle or equipment (`lats`, `glutes`, `smith`), which the name alone often
 * does not say.
 */
export function rankLibraryMatch(exercise: LibraryExercise, query: string): number | undefined {
  const byName = PlanRuntime.rankExerciseMatch(exercise.name, query);
  if (byName !== undefined) return byName;
  const facets = `${exercise.bodyPart} ${exercise.target} ${exercise.equipment} ${exercise.secondary.join(" ")}`;
  return PlanRuntime.rankExerciseMatch(facets, query) === undefined ? undefined : 4;
}
